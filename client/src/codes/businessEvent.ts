/**
 * 작업 로그 사유 코드. 공통 코드 그룹이 아니다(EVENT_REASON_CODE 그룹은 없앴다, PLAN 4장).
 * 업무 프로세스 9.3의 제안 8개만 쓴다 (ERD business_event.reason_code). 표시명은 문서에 없어 두지 않는다.
 */
export const EVENT_REASON_CODES = [
  'STOCK_FIRST',
  'FIFO_RECOMMENDATION',
  'ORDER_SHORTAGE',
  'ORDER_CANCELLED',
  'QUALITY_FAILURE',
  'SURPLUS_CONVERSION',
  'ALLOCATION_CHANGE',
  'DRAFT_CONFIRMED',
] as const;
export type EventReasonCode = (typeof EVENT_REASON_CODES)[number];
export const isEventReasonCode = (value: string): value is EventReasonCode =>
  (EVENT_REASON_CODES as readonly string[]).includes(value);
